const assert = require('node:assert/strict');
const {safeUrl, update} = require('./book_covers.js');
for (const value of ['', null, 'bad', 'javascript:alert(1)', 'data:image/png;base64,x']) assert.equal(safeUrl(value), '');
assert.equal(safeUrl('https://example.com/cover.jpg'), 'https://example.com/cover.jpg');
const image = {dataset: {}, complete: false, hidden: false, setAttribute(name, value) { this[name] = value; }, removeAttribute(name) { delete this[name]; }};
const placeholder = {hidden: false};
const container = {querySelector(selector) { return selector.includes('image') ? image : placeholder; }};
update(container, '', 'Book');
assert.equal(image.hidden, true);
assert.equal(placeholder.hidden, false);
update(container, 'https://example.com/cover.jpg', 'Book');
assert.equal(image.hidden, false);
assert.equal(placeholder.hidden, true);
image.onerror();
assert.equal(image.hidden, true);
assert.equal(placeholder.hidden, false);
image.onload();
assert.equal(image.hidden, false);
assert.equal(placeholder.hidden, true);
image.complete = true;
image.naturalWidth = 0;
update(container, 'https://example.com/cover.jpg', 'Book');
assert.equal(image.hidden, true);
image.naturalWidth = 100;
update(container, 'https://example.com/cover.jpg', 'Book');
assert.equal(image.hidden, false);
console.log('Book cover fallback tests passed.');
