const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const events = {}, documentEvents = {}, styles = {};
let anchor = {left: 24, top: 100, bottom: 144}, desktop = true, focused = false;
const panel = {style: {removeProperty(key) {delete styles[key];}, set left(v){styles.left=v;}, set top(v){styles.top=v;}, set maxHeight(v){styles['max-height']=v;}}, scrollHeight: 500, getBoundingClientRect:()=>({width:608})};
const toggle = {getBoundingClientRect:()=>anchor, focus(){focused=true;}};
const filters = {open:true, querySelector(selector){return selector==='summary'?toggle:selector==='.team-filter-panel'?panel:{addEventListener(){}};}, addEventListener(name,fn){events[name]=fn;}, contains(target){return target==='inside';}};
const context = {innerWidth:1024, innerHeight:900, window:{matchMedia:()=>({get matches(){return desktop;}}),addEventListener(name,fn){events[name]=fn;}},document:{querySelector(selector){return selector==='.team-filters'?filters:null;},addEventListener(name,fn){documentEvents[name]=fn;}}};
vm.runInNewContext(fs.readFileSync('static/js/team_roster.js','utf8'),context);
assert.equal(styles.left,'24px');assert.equal(styles.top,'152px');
anchor={left:980,top:100,bottom:144};events.resize();assert.equal(styles.left,'400px');
anchor={left:-180,top:100,bottom:144};documentEvents.scroll();assert.equal(styles.left,'16px');
anchor={left:24,top:800,bottom:844};events.resize();assert.equal(styles.top,'290px');
context.innerHeight=400;anchor={left:24,top:100,bottom:144};events.resize();assert.equal(styles['max-height'],'232px');
desktop=false;events.resize();assert.deepEqual(styles,{});
documentEvents.click({target:'inside'});assert.equal(filters.open,true);
documentEvents.keydown({key:'Escape'});assert.equal(filters.open,false);assert.equal(focused,true);
filters.open=true;documentEvents.click({target:'outside'});assert.equal(filters.open,false);
desktop=true;filters.open=true;anchor={left:24,top:-80,bottom:-36};documentEvents.scroll();assert.equal(filters.open,false);
console.log('PASS: viewport edges, scroll, vertical collision, short viewport, mobile reset, Escape/focus and outside close.');
